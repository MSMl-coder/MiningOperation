using System;
using UnityEditor;
using UnityEngine;

namespace MiningOperation.Asteroids.Editor
{
    /// <summary>Material-only editor; no texture settings are duplicated into Field Studio.</summary>
    public sealed class MOTexturedAsteroidShaderGUI : ShaderGUI
    {
        private int category;
        private string chosenPreset;
        private Material last;

        public override void OnGUI(MaterialEditor editor, MaterialProperty[] properties)
        {
            Material mat = editor.target as Material;
            if (mat == null) return;
            if (last != mat)
            {
                last = mat;
                chosenPreset = mat.GetTag(MOTexturedMaterialLibrary.Tag, false, "");
                var found = MOTexturedMaterialLibrary.Find(chosenPreset);
                if (found != null)
                {
                    string[] categories = MOTexturedMaterialLibrary.Categories;
                    category = Array.IndexOf(categories, found.category);
                    category = Mathf.Max(0, category);
                }
            }
            EditorGUILayout.LabelField("MINING OPERATION / TEXTURED SURFACE", EditorStyles.boldLabel);
            string[] labels = MOTexturedMaterialLibrary.Categories;
            category = EditorGUILayout.Popup("Rock / ice family", category, labels);
            var options = MOTexturedMaterialLibrary.ForCategory(labels[category]);
            int selected = 0;
            for (int i = 0; i < options.Length; ++i)
                if (options[i].id == chosenPreset) selected = i;
            selected = EditorGUILayout.Popup("Texture preset", selected,
                Array.ConvertAll(options, r => r.displayName));
            chosenPreset = options[selected].id;
            string active = mat.GetTag(MOTexturedMaterialLibrary.Tag, false, "");
            var current = MOTexturedMaterialLibrary.Find(active);
            EditorGUILayout.LabelField("Applied", current != null ? current.displayName : "Custom / not assigned");
            if (GUILayout.Button("Apply texture set (Albedo + Normal + Mask)"))
            {
                try { foreach (UnityEngine.Object t in editor.targets) MOTexturedMaterialLibrary.Apply(t as Material, options[selected]); }
                catch (Exception e) { Debug.LogException(e); EditorUtility.DisplayDialog("Texture preset error", e.Message, "OK"); }
            }
            EditorGUILayout.Space(8f);
            EditorGUILayout.LabelField("PBR TEXTURES", EditorStyles.boldLabel);
            Property(editor, properties, "_BaseMap", "Albedo (sRGB)");
            Property(editor, properties, "_NormalMap", "Normal map");
            Property(editor, properties, "_MaskMap", "Mask R: AO / G: Roughness / B: Metallic");
            EditorGUILayout.HelpBox("These three maps are shared by Near and Far. The shader uses local-space triplanar projection with mipmaps, no UV seams. Real silhouette craters are generated by Geometry, not painted here.", MessageType.None);
            EditorGUILayout.LabelField("TEXTURE PROJECTION", EditorStyles.boldLabel);
            Property(editor, properties, "_TextureFrequency", "Texture frequency");
            Property(editor, properties, "_TriplanarSharpness", "Triplanar sharpness");
            Property(editor, properties, "_ColorVariation", "Seed color variation");
            EditorGUILayout.LabelField("SURFACE RESPONSE", EditorStyles.boldLabel);
            Property(editor, properties, "_BaseColor", "Tint");
            Property(editor, properties, "_NormalStrength", "Normal strength");
            Property(editor, properties, "_SmoothnessMultiplier", "Smoothness multiplier");
            Property(editor, properties, "_MetallicMultiplier", "Metallic multiplier");
            Property(editor, properties, "_AOInfluence", "AO influence");
            Property(editor, properties, "_AmbientFloor", "Ambient floor");
            Property(editor, properties, "_Exposure", "Exposure");
            Property(editor, properties, "_DetailFadeStart", "Far normal fade start");
            EditorGUILayout.Space(8f);
            EditorGUILayout.LabelField("LIGHTING DIAGNOSTICS (temporary)", EditorStyles.boldLabel);
            Property(editor, properties, "_MO_DebugLighting", "Lighting debug view");
            EditorGUILayout.HelpBox("Off = normal URP PBR. MainLightOnly = main sun response without material color; ShadedNormals = after normal map; RawAlbedo = before lighting; MeshNormals = original mesh normals. Return to Off when finished. This does not change generated asteroids or save data.", MessageType.None);
            EditorGUILayout.Space();
            editor.EnableInstancingField();
            editor.RenderQueueField();
        }

        private static void Property(MaterialEditor editor, MaterialProperty[] props, string property, string label)
        {
            MaterialProperty p = FindProperty(property, props, false);
            if (p != null) editor.ShaderProperty(p, label);
        }
    }
}
